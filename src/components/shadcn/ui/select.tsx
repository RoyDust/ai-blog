const selectBodyScrollLockAttribute = "data-radix-select-open"

let openSelectCount = 0

function useSelectBodyScrollLockAttribute(open: boolean) {
  React.useEffect(() => {
    if (!open || typeof document === "undefined") return

    openSelectCount += 1
    document.body.setAttribute(selectBodyScrollLockAttribute, "true")

    return () => {
      openSelectCount = Math.max(0, openSelectCount - 1)

      if (openSelectCount === 0) {
        document.body.removeAttribute(selectBodyScrollLockAttribute)
      }
    }
  }, [open])
}

function Select({
  open: openProp,
  defaultOpen,
  onOpenChange,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Root>) {
  const [uncontrolledOpen, setUncontrolledOpen] = React.useState(
    defaultOpen ?? false
  )
  const open = openProp ?? uncontrolledOpen

  const handleOpenChange = React.useCallback(
    (nextOpen: boolean) => {
      if (openProp === undefined) {
        setUncontrolledOpen(nextOpen)
      }

      onOpenChange?.(nextOpen)
    },
    [onOpenChange, openProp]
  )

  useSelectBodyScrollLockAttribute(open)

  return (
    <SelectPrimitive.Root
      data-slot="select"
      defaultOpen={defaultOpen}
      open={openProp}
      onOpenChange={handleOpenChange}
      {...props}
    />
  )
}

